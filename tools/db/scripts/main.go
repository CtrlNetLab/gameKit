func isValid(k pref.Kind) bool {
	return k == pref.Int32Kind || k == pref.Uint32Kind || k == pref.Int64Kind ||
		k == pref.Uint64Kind || k == pref.StringKind || k == pref.MessageKind
}

func genDataFile(structName, tableName, tableOutfile string) {
	// mt, _ := preg.GlobalTypes.FindMessageByName(pref.FullName("database.PlayerData"))
	// dbData := "../../pkg/database/db_player_data.pb.go"

	mt, _ := preg.GlobalTypes.FindMessageByName(pref.FullName(structName))

	crFile, crerr := os.Create(tableOutfile)
	if crerr != nil {
		fmt.Printf("create file failed. tableOutfile: %s\n", tableOutfile)
		return
	}

	crFile.WriteString("// Code generated by tools/db. DO NOT EDIT.\n\n")

	crFile.WriteString("package database\n\n")

	// DBPlayerData
	// crFile.WriteString("type DBPlayerData struct {\n")
	crFile.WriteString(fmt.Sprintf("type %s struct {\n", tableName))
	fields := mt.Descriptor().Fields()
	for i := 0; i < fields.Len(); i++ {
		fd := fields.Get(i)
		kind := fd.Kind()

		stype := kind.String()
		if kind == pref.MessageKind {
			stype = "[]byte"
		}

		crFile.WriteString(fmt.Sprintf("\t%s%12s\t\t`gorm:\"column:%s\"`\n", fd.TextName(), stype, fd.TextName()))
	}
	crFile.WriteString("}\n")

	crFile.Close()
}

// genDBConvertFile("database.PlayerData", "DBPlayerData", "PlayerData", "../../pkg/database/player_data_convert.pb.go")

func genDBConvertFile(structName, tableName, pbName, convertOutfile string) {
	// mt, _ := preg.GlobalTypes.FindMessageByName(pref.FullName("database.PlayerData"))
	// dbConvert := "../../pkg/database/db_convert.pb.go"

	mt, _ := preg.GlobalTypes.FindMessageByName(pref.FullName(structName))

	dbFile, dberr := os.Create(convertOutfile)
	if dberr != nil {
		fmt.Printf("create file failed. DBConvert: %s\n", convertOutfile)
		return
	}

	hasBlobData := false
	fields := mt.Descriptor().Fields()
	for i := 0; i < fields.Len(); i++ {
		fd := fields.Get(i)
		kind := fd.Kind()

		if kind == pref.MessageKind {
			hasBlobData = true
		}
	}

	dbFile.WriteString("// Code generated by tools/db. DO NOT EDIT.\n\n")

	dbFile.WriteString("package database\n\n")
	dbFile.WriteString("import (\n")
	dbFile.WriteString("\t\"time\"\n")
	if hasBlobData {
		dbFile.WriteString("\t\"google.golang.org/protobuf/proto\"\n")
		dbFile.WriteString("\t\"fmt\"\n")
	}
	dbFile.WriteString(")\n\n")

	lastMessageFlag := false

	{
		// 生成函数: pb 转化成 map[string]interface {}
		// dbFile.WriteString("func Create%s(pbData * PlayerData) (* DBPlayerData, error) {\n")
		dbFile.WriteString(fmt.Sprintf("func Create%s(pbData * %s) (map[string] interface {}, error) {\n", tableName, pbName))
		if hasBlobData {
			dbFile.WriteString("\tvar err error\n")
		}
		dbFile.WriteString("\tNow := time.Now().Unix()\n\n")
		dbFile.WriteString(fmt.Sprintf("\tdbData := make(map[string]interface {})\n\n"))

		for i := 0; i < fields.Len(); i++ {
			fd := fields.Get(i)
			kind := fd.Kind()
			textName := fd.TextName()

			if textName == "Id" || textName == "id" {
				// 自增主键
				continue
			}

			if textName == "UpdateAt" {
				dbFile.WriteString(fmt.Sprintf("\tdbData[\"%s\"] = Now\n", textName))
				continue
			}

			if kind != pref.MessageKind {
				if lastMessageFlag {
					dbFile.WriteString("\n")
				}
				// 普通字段
				dbFile.WriteString(fmt.Sprintf("\tdbData[\"%s\"] %10s pbData.%s\n", textName, "=", textName))
				lastMessageFlag = false
			} else {
				// 二进制字段
				// dbFile.WriteString(fmt.Sprintf("\n\t%sDataSize := pbData.%s.Size()\n", textName, textName))
				// dbFile.WriteString(fmt.Sprintf("\n\t%sDataSize := proto.Size(pbData.%s)\n", textName, textName))
				// dbFile.WriteString(fmt.Sprintf("\tdbData_%s := make([]byte, %sDataSize, %sDataSize)\n", textName, textName, textName))
				// dbFile.WriteString(fmt.Sprintf("\t_, err = pbData.%s.MarshalTo(dbData_%s)\n", textName, textName))
				dbFile.WriteString(fmt.Sprintf("\tdbData_%s, err := proto.Marshal(pbData.%s)\n", textName, textName))
				dbFile.WriteString("\tif err != nil {\n")
				dbFile.WriteString(fmt.Sprintf("\t\treturn nil, fmt.Errorf(\"MarshalTo %s failed. Err: %%v\", err)\n", textName))
				dbFile.WriteString("\t} else {\n")
				dbFile.WriteString(fmt.Sprintf("\t\tdbData[\"%s\"] = dbData_%s\n", textName, textName))
				dbFile.WriteString("\t}\n")

				lastMessageFlag = true
			}
		}

		dbFile.WriteString("\n\treturn dbData, nil\n")
		dbFile.WriteString("}\n\n")
	}

	{
		// 生成函数: db 转化成 pb
		dbFile.WriteString(fmt.Sprintf("func CreatePB%s(dbData * %s) (* %s, error) {\n", pbName, tableName, pbName))
		dbFile.WriteString(fmt.Sprintf("\tpbData := &%s{}\n\n", pbName))

		lastMessageFlag = false
		for i := 0; i < fields.Len(); i++ {
			fd := fields.Get(i)
			kind := fd.Kind()
			textName := fd.TextName()

			if kind != pref.MessageKind {
				if lastMessageFlag {
					dbFile.WriteString("\n")
				}
				// 普通字段
				dbFile.WriteString(fmt.Sprintf("\tpbData.%s = dbData.%s\n", textName, textName))
				lastMessageFlag = false
			} else {
				dbFile.WriteString(fmt.Sprintf("\n\tpbData.%s = &%s{}\n", textName, fd.Name()))
				dbFile.WriteString(fmt.Sprintf("\tif len(dbData.%s) > 0 {\n", textName))
				dbFile.WriteString(fmt.Sprintf("\t\tif err := proto.Unmarshal(dbData.%s, pbData.%s); err != nil {\n", textName, textName))
				dbFile.WriteString(fmt.Sprintf("\t\t\treturn nil, fmt.Errorf(\"Unmarshal %s failed. Err: %%#v\", err)\n", textName))
				dbFile.WriteString("\t\t}\n")
				dbFile.WriteString("\t}\n")
				lastMessageFlag = true
			}
		}

		dbFile.WriteString("\treturn pbData, nil\n")
		dbFile.WriteString("}\n\n")
	}
	{
		// 生成函数: map[string] interface {} 转化成 db
		dbFile.WriteString(fmt.Sprintf("func Create%sByMap(dbMap map[string] interface {}) (* %s, error) {\n", tableName, tableName))
		dbFile.WriteString(fmt.Sprintf("\tdbData := &%s{}\n\n", tableName))

		for i := 0; i < fields.Len(); i++ {
			fd := fields.Get(i)
			kind := fd.Kind()
			textName := fd.TextName()

			stype := kind.String()
			if kind == pref.MessageKind {
				stype = "[]byte"
			}

			dbFile.WriteString(fmt.Sprintf("\tif v, ok := dbMap[\"%s\"]; ok {\n", textName))
			dbFile.WriteString(fmt.Sprintf("\t\tif vv, vok := v.(%s); vok {\n", stype))
			dbFile.WriteString(fmt.Sprintf("\t\t\tdbData.%s = vv\n", textName))
			dbFile.WriteString("\t\t}\n")
			dbFile.WriteString("\t}\n")
		}

		dbFile.WriteString("\n\treturn dbData, nil\n")
		dbFile.WriteString("}\n\n")
	}

	{
		// 生成函数: map 转化成 pb
		dbFile.WriteString(fmt.Sprintf("func CreatePB%sByMap(dbData map[string] interface {}) (* %s, error) {\n", pbName, pbName))
		dbFile.WriteString(fmt.Sprintf("\tpbData := &%s{}\n\n", pbName))

		lastMessageFlag = false
		for i := 0; i < fields.Len(); i++ {
			fd := fields.Get(i)
			kind := fd.Kind()
			textName := fd.TextName()

			stype := kind.String()
			if kind == pref.MessageKind {
				stype = "[]byte"
			}

			// dbFile.WriteString(fmt.Sprintf("\tvar (\n\tdbData_%s %s\n\tvvok bool = false\n\t)\n", textName, stype))

			if kind != pref.MessageKind {
				if lastMessageFlag {
					dbFile.WriteString("\n")
				}
				// 普通字段
				dbFile.WriteString(fmt.Sprintf("\tif v, vok := dbData[\"%s\"]; vok {\n", textName))
				dbFile.WriteString(fmt.Sprintf("\t\tif dbData_%s, vvok := v.(%s); vvok {\n", textName, stype))
				dbFile.WriteString(fmt.Sprintf("\t\t\tpbData.%s = dbData_%s\n", textName, textName))
				dbFile.WriteString(fmt.Sprintf("\t\t}\n\t}\n"))

				lastMessageFlag = false
			} else {
				dbFile.WriteString(fmt.Sprintf("\n\tpbData.%s = &%s{}\n", textName, fd.Name()))
				dbFile.WriteString(fmt.Sprintf("\tif v, vok := dbData[\"%s\"]; vok {\n", textName))
				dbFile.WriteString(fmt.Sprintf("\t\tif dbData_%s, vvok := v.(%s); vvok && len(dbData_%s) > 0 {\n", textName, stype, textName))
				// dbFile.WriteString(fmt.Sprintf("\t\t\tif err := pbData.%s.Unmarshal(dbData_%s); err != nil {\n", textName, textName))
				dbFile.WriteString(fmt.Sprintf("\t\t\tif err := proto.Unmarshal(dbData_%s, pbData.%s); err != nil {\n", textName, textName))
				dbFile.WriteString(fmt.Sprintf("\t\t\t\treturn nil, fmt.Errorf(\"Unmarshal %s failed. Err: %%#v\", err)\n", textName))
				dbFile.WriteString("\t\t\t}\n")
				dbFile.WriteString("\t\t}\n")
				dbFile.WriteString("\t}\n")

				lastMessageFlag = true
			}
		}

		dbFile.WriteString("\treturn pbData, nil\n")
		dbFile.WriteString("}\n\n")
	}

	dbFile.Close()
}

// genTableFile("database.PlayerData", "DBPlayerData", "../../run/tools/db/DBPlayerData.tmpl.sql", "AccId", "AccId")
func genTableFile(structName, tableName, sqlOutfile, primary, indexsStr, indexName string) {
	mt, _ := preg.GlobalTypes.FindMessageByName(pref.FullName(structName))

	table := sqlOutfile

	tableFile, terr := os.Create(table)
	if terr != nil {
		fmt.Printf("create file failed. Table: %s, terr: %#v\n", table, terr)
		return
	}

	tableFile.WriteString("-- Code generated by tools/db. DO NOT EDIT.\n\n")
	tableFile.WriteString(fmt.Sprintf("CREATE TABLE IF NOT EXISTS `%s_{{idx}}` (\n", tableName))

	kind2SQL := map[pref.Kind]string{
		pref.Int32Kind:  "INT SIGNED",
		pref.Uint32Kind: "INT UNSIGNED",
		pref.Int64Kind:  "BIGINT SIGNED",
		pref.Uint64Kind: "BIGINT UNSIGNED",
		// 当前所有的 string 都用 VARCHAR(64), 普通字段里一般都只保存名字
		pref.StringKind:  "TEXT NOT NULL",
		pref.MessageKind: "MEDIUMBLOB",
	}

	fields := mt.Descriptor().Fields()
	var hasInCrement bool
	for i := 0; i < fields.Len(); i++ {
		fd := fields.Get(i)
		kind := fd.Kind()
		if fd.TextName() == "Id" || fd.TextName() == "id" {
			hasInCrement = true
			tableFile.WriteString(fmt.Sprintf("\t`%s` %s,\n", fd.TextName(), "BIGINT UNSIGNED NOT NULL AUTO_INCREMENT"))
			continue
		} else {
			if (strings.Contains(primary, fd.TextName()) || strings.Contains(indexsStr, fd.TextName())) && kind == pref.StringKind {
				tableFile.WriteString(fmt.Sprintf("\t`%s` %s,\n", fd.TextName(), "VARCHAR(128) NOT NULL"))
			} else {
				tableFile.WriteString(fmt.Sprintf("\t`%s` %s,\n", fd.TextName(), kind2SQL[kind]))
			}
		}
	}

	if primary != "" {
		tableFile.WriteString(fmt.Sprintf("\tPRIMARY KEY(`%s`),\n", primary))
	}
	if indexsStr != "" {
		indexs := strings.Split(indexsStr, ";")
		for i, index := range indexs {
			keys := strings.Split(index, ",")
			tableFile.WriteString(fmt.Sprintf("\tINDEX `"))
			if indexName == "" {
				for index, key := range keys {
					if index == 0 {
						tableFile.WriteString(fmt.Sprintf("%s", key))
					} else {
						tableFile.WriteString(fmt.Sprintf("_%s", key))
					}
				}
				tableFile.WriteString(fmt.Sprintf("_index` (`"))
			} else {
				tableFile.WriteString(fmt.Sprintf("%s` (`", indexName))
			}
			for index, key := range keys {
				if index == 0 {
					tableFile.WriteString(fmt.Sprintf("%s", key))
				} else {
					tableFile.WriteString(fmt.Sprintf("`,`%s", key))
				}
			}
			if i+1 == len(indexs) {
				tableFile.WriteString(fmt.Sprintf("`)\n"))
			} else {
				tableFile.WriteString(fmt.Sprintf("`),\n"))
			}
		}
	}

	if hasInCrement {
		tableFile.WriteString(") ENGINE=InnoDB AUTO_INCREMENT=1 DEFAULT CHARSET=UTF8MB4 COLLATE=utf8mb4_unicode_ci;\n")
	} else {
		tableFile.WriteString(") ENGINE=InnoDB DEFAULT CHARSET=UTF8MB4 COLLATE=utf8mb4_unicode_ci;\n")
	}
}

func checkField(structName string) {
	mt, _ := preg.GlobalTypes.FindMessageByName(pref.FullName(structName))
	if mt == nil {
		return
	}

	fields := mt.Descriptor().Fields()
	for i := 0; i < fields.Len(); i++ {
		fd := fields.Get(i)
		kind := fd.Kind()

		if !isValid(kind) {
			fmt.Printf("invalid kind. just can use: int32/uint32/int64/uint64/message\n")
			os.Exit(1)
		}
	}
}

