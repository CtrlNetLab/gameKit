package main

import (
	"flag"
	"fmt"
	"log"
	"net"
	"os"
	"os/user"
	"strings"
	"time"

	git "github.com/go-git/go-git/v5"
	"github.com/shirou/gopsutil/host"
)

type repositoryInfo struct {
	Branch  string
	Commit  string
	Author  string
	Date    string
	Message string
}

type submoduleInfo struct {
	Path    string
	Branch  string
	Commit  string
	Author  string
	Date    string
	Message string
}

type buildInfo struct {
	BuildDate      string
	BuildDirectory string
	BuildUser      string
	BuildHostname  string
	BuildHostIPs   []string
	Repository     repositoryInfo
	Submodules     []submoduleInfo
}

// getGitInfo retrieves information about the current git repository
func getGitInfo(gitDir string) (*buildInfo, error) {
	repo, err := git.PlainOpen(gitDir)
	if err != nil {
		return nil, err
	}

	ref, err := repo.Head()
	if err != nil {
		return nil, err
	}
	branch := ref.Name().Short()

	commit, err := repo.CommitObject(ref.Hash())
	if err != nil {
		return nil, err
	}
	repoInfo := repositoryInfo{
		Branch:  branch,
		Commit:  commit.Hash.String(),
		Author:  commit.Author.String(),
		Date:    commit.Author.When.Format(time.RFC3339),
		Message: strings.TrimSpace(commit.Message),
	}

	var submodules []submoduleInfo

	worktree, err := repo.Worktree()
	if err != nil {
		return nil, err
	}

	submoduleRefs, err := worktree.Submodules()
	if err != nil {
		return nil, err
	}

	for _, submoduleRef := range submoduleRefs {
		submodule := submoduleRef.Config()
		subRepo, err := submoduleRef.Repository()
		if err != nil {
			return nil, err
		}

		subRef, err := subRepo.Head()
		if err != nil {
			return nil, err
		}

		subCommit, err := subRepo.CommitObject(subRef.Hash())
		if err != nil {
			return nil, err
		}

		submodules = append(submodules, submoduleInfo{
			Path:    submodule.Path,
			Branch:  subRef.Name().Short(),
			Commit:  subCommit.Hash.String(),
			Author:  subCommit.Author.String(),
			Date:    subCommit.Author.When.Format(time.RFC3339),
			Message: strings.TrimSpace(subCommit.Message),
		})
	}

	currentUser, err := user.Current()
	if err != nil {
		return nil, err
	}

	hostInfo, err := host.Info()
	if err != nil {
		return nil, err
	}

	interfaces, err := net.Interfaces()
	if err != nil {
		return nil, err
	}

	var ips []string
	for _, i := range interfaces {
		if i.Flags&net.FlagLoopback == 0 && i.Flags&net.FlagUp != 0 {
			addrs, err := i.Addrs()
			if err != nil {
				return nil, err
			}
			for _, addr := range addrs {
				ip := strings.Split(addr.String(), "/")[0]
				ips = append(ips, ip)
			}
		}
	}

	buildDir, err := os.Getwd()
	if err != nil {
		return nil, err
	}

	return &buildInfo{
		BuildDate:      time.Now().Format(time.RFC3339),
		BuildDirectory: buildDir,
		BuildUser:      currentUser.Username,
		BuildHostname:  hostInfo.Hostname,
		BuildHostIPs:   ips,
		Repository:     repoInfo,
		Submodules:     submodules,
	}, nil
}

// generateBuildInfoGo generates the build.go file with the provided build information
func generateBuildInfoGo(info *buildInfo, outputFile string) {
	fileContent := fmt.Sprintf(`// Code generated by tools/buildInfo/cmd/main.go. DO NOT EDIT.

package control

type repositoryInfo struct {
	Branch  string
	Commit  string
	Author  string
	Date    string
	Message string
}

type submoduleInfo struct {
	Path    string
	Branch  string
	Commit  string
	Author  string
	Date    string
	Message string
}

type buildInfo struct {
	BuildDate      string
	BuildDirectory string
	BuildUser      string
	BuildHostname  string
	BuildHostIPs   []string
	Repository     repositoryInfo
	Submodules     []submoduleInfo
}

var BuildInfo = buildInfo{
	BuildDate:      %q,
	BuildDirectory: %q,
	BuildUser:      %q,
	BuildHostname:  %q,
	BuildHostIPs:   []string{
`, info.BuildDate, info.BuildDirectory, info.BuildUser, info.BuildHostname)

	for _, ip := range info.BuildHostIPs {
		fileContent += fmt.Sprintf(`		%q,
`, ip)
	}

	fileContent += fmt.Sprintf(`	},
	Repository: repositoryInfo{
		Branch:  %q,
		Commit:  %q,
		Author:  %q,
		Date:    %q,
		Message: %q,
	},
	Submodules: []submoduleInfo{
`, info.Repository.Branch, info.Repository.Commit, info.Repository.Author, info.Repository.Date, info.Repository.Message)

	for _, submodule := range info.Submodules {
		fileContent += fmt.Sprintf(`		{
			Path:    %q,
			Branch:  %q,
			Commit:  %q,
			Author:  %q,
			Date:    %q,
			Message: %q,
		},
`, submodule.Path, submodule.Branch, submodule.Commit, submodule.Author, submodule.Date, submodule.Message)
	}

	fileContent += `	},
}
`

	err := os.WriteFile(outputFile, []byte(fileContent), 0644)
	if err != nil {
		log.Fatalf("failed to write build.go: %v", err)
	}

	fmt.Printf("%s has been generated.\n", outputFile)
}

func main() {
	gitDir := flag.String("git-dir", ".", "path to the git directory")
	outputFile := flag.String("output", "build.go", "output file name")
	flag.Parse()

	gitInfo, err := getGitInfo(*gitDir)
	if err != nil {
		log.Fatalf("failed to get git info: %v", err)
	}
	generateBuildInfoGo(gitInfo, *outputFile)
}
